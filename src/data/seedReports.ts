export function getInitialSeedReports(): CivicIssue[] {
  const now = new Date();

  return RAW_SEEDS.map((item) => {
    const createdDate = new Date(now.getTime() - item.hoursAgo * 60 * 60 * 1000);
    const updatedDate = new Date(createdDate.getTime() + Math.min(item.hoursAgo * 0.4, 24) * 60 * 60 * 1000);

    const slaHours = item.isEmergency ? 24 : item.sev >= 7 ? 48 : 72;
    const slaDeadline = new Date(createdDate.getTime() + slaHours * 60 * 60 * 1000).toISOString();

    const timeline: { status: CivicIssue['status']; timestamp: string; note: string; actor: string }[] = [
      {
        status: 'Submitted',
        timestamp: createdDate.toISOString(),
        note: 'Issue reported with verified GPS coordinates and photo evidence.',
        actor: 'Citizen App',
      },
    ];

    if (item.status !== 'Submitted') {
      timeline.push({
        status: 'Verified' as const,
        timestamp: new Date(createdDate.getTime() + 15 * 60 * 1000).toISOString(),
        note: `AI Vision analysis validated hazard rating (Severity: ${item.sev}/10). Auto-routed to ${item.dept}.`,
        actor: 'Civic Pulse AI Engine',
      });
    }

    if (item.status === 'Assigned' || item.status === 'In Progress' || item.status === 'Resolved') {
      timeline.push({
        status: 'Assigned' as const,
        timestamp: new Date(createdDate.getTime() + 45 * 60 * 1000).toISOString(),
        note: `Assigned to ${item.team || 'Municipal Fast Response Team'}. Work order dispatched.`,
        actor: 'Central Dispatch Control',
      });
    }

    if (item.status === 'In Progress' || item.status === 'Resolved') {
      timeline.push({
        status: 'In Progress' as const,
        timestamp: new Date(createdDate.getTime() + 120 * 60 * 1000).toISOString(),
        note: 'Field crew mobilized on site with repair machinery and supplies.',
        actor: item.team || 'Field Crew',
      });
    }

    if (item.status === 'Resolved') {
      timeline.push({
        status: 'Resolved' as const,
        timestamp: updatedDate.toISOString(),
        note: 'Repair completed. Fix photo validated by AI inspector with 94%+ confidence score.',
        actor: item.team || 'Field Supervisor',
      });
    }

    const comments = [
      {
        id: `c1-${item.id}`,
        user: 'Aarav Mehta',
        text: 'I passed by this morning, it was very chaotic. Glad it is tracked here!',
        timestamp: new Date(createdDate.getTime() + 30 * 60 * 1000).toISOString(),
      },
      {
        id: `c2-${item.id}`,
        user: 'Municipal Dispatch',
        text: `Work ticket #${item.id} logged in municipal maintenance register. Priority: ${item.isEmergency ? 'EMERGENCY' : 'STANDARD'}.`,
        timestamp: new Date(createdDate.getTime() + 50 * 60 * 1000).toISOString(),
        isOfficial: true,
      },
    ];

    const nodalAgency =
      item.cat === 'Street Light'
        ? 'BESCOM'
        : item.cat === 'Water Leakage'
        ? 'BWSSB'
        : 'BBMP';

    return {
      id: item.id,
      title: item.title,
      description: item.desc,
      category: item.cat,
      status: item.status,
      severity: item.sev,
      sizeEstimate: item.size,
      safetyHazards: item.hazards,
      isEmergency: item.isEmergency,
      department: item.dept,
      nodalAgency,
      assignedTeam: item.team,
      juniorEngineer: 'Er. Suresh Gowda (AEE Ward Nodal Officer)',
      lat: item.lat,
      lng: item.lng,
      address: item.address,
      ward: item.ward,
      upvotes: item.upvotes,
      upvotedByMe: false,
      reporterName: item.id.endsWith('1') || item.id.endsWith('5') ? 'Civic Vigilante' : 'Priya Sharma',
      isAnonymous: item.id.endsWith('7'),
      createdAt: createdDate.toISOString(),
      updatedAt: updatedDate.toISOString(),
      slaHours,
      slaDeadline,
      estimatedCostINR: item.cost * 45, // Convert to realistic INR (e.g. ₹4,500 - ₹35,000)
      images: [item.img],
      resolutionPhoto: item.fixImg,
      resolutionConfidence: item.fixImg ? 95 : undefined,
      resolutionNotes: item.fixImg ? 'Asphalt compacted with vibrating roller and sealed flush with road grade.' : undefined,
      citizenConfirmed: item.status === 'Resolved',
      whatsappUpdatesEnabled: true,
      comments,
      timeline,
    };
  });
}
